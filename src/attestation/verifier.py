"""SLSA Provenance & Cryptographic Signature Verifier."""

import base64
import hashlib
import json
import logging
from typing import Any, Dict, List, Tuple
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import padding, rsa

logger = logging.getLogger(__name__)


class AttestationVerifier:
    """Verifies in-toto and SLSA v0.2 / v1.0 provenance attestations."""

    def __init__(self, policy: Dict[str, Any]):
        self.policy = policy
        self.trusted_builders = set(self.policy.get("trusted_builders", []))
        self.min_slsa = self.policy.get("minimum_slsa_level", 3)

    def verify_provenance(
        self,
        attestation_data: Dict[str, Any],
        expected_artifact_sha256: str
    ) -> Tuple[bool, List[Dict[str, Any]]]:
        """Validates SLSA predicate, builder identity, and artifact hash binding."""
        violations = []

        predicate = attestation_data.get("predicate", {})
        builder = predicate.get("builder", {}).get("id", "")
        build_type = predicate.get("buildType", "")

        # 1. Trusted Builder Verification
        is_trusted_builder = any(tb in builder for tb in self.trusted_builders)
        if not is_trusted_builder:
            violations.append({
                "rule_id": "SLSA-PROV-01",
                "severity": "CRITICAL",
                "title": f"Untrusted Build Runner: '{builder}'",
                "description": f"Provenance statement generated by unapproved builder. Allowed: {list(self.trusted_builders)}",
                "remediation": "Configure builds to execute strictly on authorized, tamper-proof CI runners."
            })

        # 2. Artifact Digest Integrity Check
        subjects = attestation_data.get("subject", [])
        matched_hash = False
        for s in subjects:
            digest = s.get("digest", {}).get("sha256", "")
            if digest.lower() == expected_artifact_sha256.lower():
                matched_hash = True
                break

        if not matched_hash:
            violations.append({
                "rule_id": "SLSA-PROV-02",
                "severity": "CRITICAL",
                "title": "Artifact Digest Hash Mismatch",
                "description": f"Attestation subject digest does not match binary artifact hash '{expected_artifact_sha256}'. Evidence of post-build tampering.",
                "remediation": "Do not deploy artifact; trigger emergency supply-chain tamper investigation."
            })

        # 3. Source Material Immutability Check
        materials = predicate.get("materials", [])
        for m in materials:
            commit_digest = m.get("digest", {}).get("sha1") or m.get("digest", {}).get("sha256")
            if not commit_digest:
                violations.append({
                    "rule_id": "SLSA-PROV-03",
                    "severity": "HIGH",
                    "title": f"Mutable Source Material: {m.get('uri')}",
                    "description": "Source repository URI not pinned to cryptographic commit SHA.",
                    "remediation": "Ensure CI/CD provenance stamps immutable commit SHA into attestation predicate."
                })

        is_valid = len(violations) == 0
        return is_valid, violations
